import fs from 'fs-extra';
import path from 'path';
import YAML from 'yaml';
import { INTENT_CATEGORIES } from './constants.js';

/**
 * Sanitizes a page ID so it can never escape `.seo/pages/`.
 */
export function sanitizePageId(id) {
    const cleaned = String(id || 'page')
        .replace(/[^a-zA-Z0-9_-]/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-+|-+$/g, '');
    return cleaned || 'page';
}

function mergePagesById(existingPages = [], incomingPages = []) {
    const map = new Map();
    for (const p of existingPages) {
        if (p && p.id) map.set(p.id, p);
    }
    for (const p of incomingPages) {
        if (p && p.id) map.set(p.id, p);
    }
    return Array.from(map.values());
}

/**
 * Writes (and merges) platform analysis metrics into `.seo/STATUS.yml`.
 *
 * @param {any} _doc - Deprecated parameter kept for backwards signature compatibility
 * @param {any} response - API response from analyze/sync
 * @param {string} cwd - Project root directory
 * @param {{ provider?: string }} [options]
 */
export async function writeAnalysisToSeoMd(_doc, response, cwd, options = {}) {
    const seomdDir = path.join(cwd, '.seo');
    await fs.ensureDir(seomdDir);
    const statusPath = path.join(seomdDir, 'STATUS.yml');

    let existing = {};
    if (await fs.pathExists(statusPath)) {
        try {
            existing = YAML.parse(await fs.readFile(statusPath, 'utf8')) || {};
        } catch {
            existing = {};
        }
    }

    const aeo = response?.aeo_analysis || {};
    const incomingPages = Array.isArray(response?.page_analysis)
        ? response.page_analysis.map((p) => ({
            id: p.id,
            url: p.url,
            citation_rate: p.citation_rate ?? null,
            gap_score: p.gap_score ?? null,
            top_cited_competitor: p.top_cited_competitor ?? null,
        }))
        : [];

    const existingPages = Array.isArray(existing?.pages?.pages) ? existing.pages.pages : [];
    const mergedPages = mergePagesById(existingPages, incomingPages);

    const mergedIntent = { ...(existing.intent || {}) };
    if (response?.intent_analysis && typeof response.intent_analysis === 'object') {
        for (const cat of INTENT_CATEGORIES) {
            if (response.intent_analysis[cat]) {
                mergedIntent[cat] = {
                    citation_rate: response.intent_analysis[cat].citation_rate ?? null,
                    top_cited_competitor: response.intent_analysis[cat].top_cited_competitor ?? null,
                    gap_score: response.intent_analysis[cat].gap_score ?? null,
                    trend: response.intent_analysis[cat].trend || 'stable',
                };
            }
        }
    }

    const source = response?.provider || options.provider || existing.source || 'custom';

    const statusData = {
        source,
        last_analyzed: aeo.last_analyzed ?? existing.last_analyzed ?? null,
        next_analysis: aeo.next_analysis ?? existing.next_analysis ?? null,
        aeo: {
            overall_citation_rate: aeo.overall_citation_rate ?? existing.aeo?.overall_citation_rate ?? null,
            overall_gap_score: aeo.overall_gap_score ?? existing.aeo?.overall_gap_score ?? null,
            engines_tracked: aeo.engines_tracked ?? existing.aeo?.engines_tracked ?? [],
        },
        intent: mergedIntent,
        pages: {
            pages: mergedPages,
            missing_pages: existing.pages?.missing_pages || [],
            build_order_recommendation: existing.pages?.build_order_recommendation || [],
        },
        keywords: existing.keywords || {},
    };

    const header = [
        '# .seo/STATUS.yml',
        '#',
        '# Auto-generated by your connected SEO.md provider.',
        '# Do not edit manually — run `npx seomd-cli analyze` or `npx seomd-cli sync` to update.',
        '',
    ].join('\n');

    await fs.writeFile(statusPath, `${header}\n${YAML.stringify(statusData)}`, 'utf8');
}

export const writeStatusYml = writeAnalysisToSeoMd;

/**
 * Generates and merges `.seo/REVERSE.md`.
 *
 * @param {string} cwd - Project root directory
 * @param {any} response - API response from analyze/sync
 * @param {string} [defaultDomain='example.com']
 * @param {string} [defaultBrand='My Brand']
 * @param {{ provider?: string }} [options]
 */
export async function writeReverseMd(
    cwd,
    response,
    defaultDomain = 'example.com',
    defaultBrand = 'My Brand',
    options = {}
) {
    const seomdDir = path.join(cwd, '.seo');
    await fs.ensureDir(seomdDir);
    const reversePath = path.join(seomdDir, 'REVERSE.md');

    let existing = {};
    if (await fs.pathExists(reversePath)) {
        try {
            existing = YAML.parse(await fs.readFile(reversePath, 'utf8')) || {};
        } catch {
            existing = {};
        }
    }

    const incomingPages = Array.isArray(response?.page_analysis)
        ? response.page_analysis.map((p) => ({
            id: p.id,
            url: p.url,
            status: p.status || 'planned',
            citation_rate: p.citation_rate ?? null,
            gap_score: p.gap_score ?? null,
            top_cited_competitor: p.top_cited_competitor ?? null,
            why_page_won: p.why_page_won || [],
            citation_hooks: p.citation_hooks || [],
            gaps_for_brand: p.gaps_for_brand || p.gaps_for_my_brand || [],
            remediation_playbook: p.remediation_playbook || [],
            fastest_win: p.fastest_win || { action: null, estimated_gap_score_improvement: null, effort: null },
            suggested_content_outline: p.suggested_content_outline || [],
        }))
        : [];

    const existingPages = Array.isArray(existing.pages) ? existing.pages : [];
    const mergedPages = mergePagesById(existingPages, incomingPages);

    const aeo = response?.aeo_analysis || {};
    const primaryCompetitor =
        response?.intent_analysis?.comparison?.top_cited_competitor ||
        existing.primary_competitor ||
        null;

    const source = response?.provider || options.provider || existing.source || 'custom';

    const reverseDoc = {
        domain: response?.domain || existing.domain || defaultDomain,
        brand: response?.brand_name || existing.brand || defaultBrand,
        primary_competitor: primaryCompetitor,
        last_analyzed: aeo.last_analyzed ?? existing.last_analyzed ?? null,
        next_analysis: aeo.next_analysis ?? existing.next_analysis ?? null,
        source,
        pages: mergedPages,
        ...(Array.isArray(existing.competitors) ? { competitors: existing.competitors } : {}),
    };

    const header = [
        '# .seo/REVERSE.md',
        '#',
        '# Auto-generated by your connected SEO.md provider.',
        '# Do not edit manually — run `npx seomd-cli analyze` or `npx seomd-cli sync` to update.',
        '',
    ].join('\n');

    await fs.writeFile(reversePath, `${header}\n${YAML.stringify(reverseDoc)}`, 'utf8');
}

/**
 * Writes individual page playbooks into `.seo/pages/{sanitized-id}.md`.
 *
 * @param {string} cwd - Project root directory
 * @param {any} response - API response from analyze/sync
 */
export async function writePageAnalysis(cwd, response) {
    const pagesDir = path.resolve(cwd, '.seo', 'pages');
    await fs.ensureDir(pagesDir);

    const pages = Array.isArray(response?.page_analysis) ? response.page_analysis : [];
    for (const page of pages) {
        if (page && page.markdown_content) {
            const safeId = sanitizePageId(page.id);
            const filePath = path.resolve(pagesDir, `${safeId}.md`);
            if (!filePath.startsWith(pagesDir + path.sep)) {
                continue;
            }
            await fs.writeFile(filePath, page.markdown_content, 'utf8');
        }
    }
}
