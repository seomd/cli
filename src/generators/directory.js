import fs from 'fs-extra';
import path from 'path';

/**
 * Creates the .seo/ intelligence workspace directory with a README.
 * Does NOT pre-create empty placeholder page files — per-page playbooks
 * are materialized on demand when `analyze` or `sync` runs.
 *
 * @param {string} cwd - Project root directory
 * @param {object} answers - Scaffolding inputs (brand, domain)
 */
export async function createSeomdDir(cwd, answers) {
    const { brand, domain } = answers;
    const seomdDir = path.join(cwd, '.seo');

    await fs.ensureDir(path.join(seomdDir, 'pages'));

    const readmePath = path.join(seomdDir, 'README.md');
    if (!(await fs.pathExists(readmePath))) {
        await fs.writeFile(readmePath, generateSeomdReadme(brand, domain), 'utf8');
    }
}

function generateSeomdReadme(brand, domain) {
    return `# .seo/

AI search & citation intelligence workspace for **${brand}** (${domain})
Generated by SEO.md CLI — https://seomd.dev

## What is this?

\`.seo/\` stores provider-generated intelligence from citation audits, competitor analysis, and reverse-engineered playbooks. It lives alongside your source code so SEO/AEO strategy and diffs are version-controlled and reviewable in PRs.

## Directory Structure

\`\`\`
.seo/
├── pages/          # per-page playbooks (created on analyze/sync)
├── STATUS.yml      # gap scores and citation metrics (provider generated)
└── REVERSE.md      # competitor playbooks (provider generated)
\`\`\`

## Local Commands (Zero API Key Required)

\`\`\`bash
# Validate SEO.md syntax and schema
npx seomd-cli validate

# Audit local HTML / build output or localhost against SEO.md
npx seomd-cli check ./out
npx seomd-cli check http://localhost:3000

# Generate robots.txt, llms.txt, or JSON-LD from SEO.md
npx seomd-cli generate robots --out public/robots.txt
npx seomd-cli generate llms --out public/llms.txt
npx seomd-cli generate schema

# Check repo health, agent wiring, and provider config
npx seomd-cli doctor
\`\`\`

## Live Intelligence Commands (Requires a Connected Provider)

\`\`\`bash
# Run a live AI citation audit
npx seomd-cli analyze

# Pull cached provider intelligence
npx seomd-cli sync

# View current citation rates and gap scores
npx seomd-cli status
npx seomd-cli status --json
\`\`\`

## File Ownership

| Path | Owner | Editable? |
|------|-------|-----------|
| \`SEO.md\` | you | yes |
| \`.seo/STATUS.yml\` | provider | no |
| \`.seo/REVERSE.md\` | provider | no |
| \`.seo/pages/*.md\` | provider | no |

Provider-generated files are updated on each \`analyze\` or \`sync\`.
`;
}
