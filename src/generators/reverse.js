import YAML from 'yaml';
import { SPEC_VERSION, VALID_SITE_TYPES } from '../utils/constants.js';
import { normalizeDomain } from './seomd.js';

/**
 * Generates the initial .seo/REVERSE.md scaffold using safe YAML serialization.
 *
 * @param {object} answers - Scaffolding inputs (brand, domain, site_type, competitors)
 * @returns {string}
 */
export function generateReverseMd(answers) {
    const siteType = answers.site_type || 'saas';
    if (!VALID_SITE_TYPES.includes(siteType)) {
        throw new Error(`Invalid site type '${siteType}'. Must be one of: ${VALID_SITE_TYPES.join(', ')}`);
    }

    const domain = normalizeDomain(answers.domain || 'example.com');
    const brand = String(answers.brand || 'My Brand').trim();
    const competitorList = Array.isArray(answers.competitors)
        ? answers.competitors.map(normalizeDomain).filter(Boolean)
        : [];

    const doc = {
        spec: SPEC_VERSION,
        domain,
        brand,
        primary_competitor: competitorList[0] || null,
        last_analyzed: null,
        next_analysis: null,
        source: null,
        pages: [],
        competitors: competitorList.map((c) => ({
            domain: c,
            overall_citation_rate: null,
            strongest_intent_category: null,
            weakest_intent_category: null,
            top_cited_pages: [],
            citation_patterns: [],
            last_analyzed: null,
        })),
    };

    const header = [
        '# .seo/REVERSE.md',
        '#',
        '# Auto-generated by your connected SEO.md provider.',
        '# Do not edit manually — run `npx seomd-cli analyze` or `npx seomd-cli sync` to update.',
        '',
    ].join('\n');

    return `${header}\n${YAML.stringify(doc, { lineWidth: 100 })}`;
}
